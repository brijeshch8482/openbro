"""Model-written long-term memories (harness piece 3, memory L1).

One memory = one Markdown file with frontmatter, readable and editable by
the user:

    ---
    id: 3f2a…            (uuid — stable across machines)
    name: prefers-short-replies
    description: User wants short Hinglish replies, no tutorial tone
    type: feedback        user | feedback | project | reference
    scope: global         global | project:<repo root>
    created: 2026-11-26
    updated: 2026-11-26
    ---
    Short Hinglish replies, no step-by-step lectures unless asked.

Files live in `<storage>/memory/notes/<owner>/`. `INDEX.md` next to them
is generated by code from the frontmatter — never edited by the model, so
a weak model cannot corrupt it.

Storage sits behind `NoteStore` so a server backend can replace the
folder later (`storage.backend: remote`).
"""

from __future__ import annotations

import re
import uuid
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Protocol

import yaml

from openbro.memory import store
from openbro.memory.ranking import bm25_scores

NOTE_TYPES = ("user", "feedback", "project", "reference")
_SLUG_RE = re.compile(r"[^a-z0-9]+")


def slugify(name: str) -> str:
    slug = _SLUG_RE.sub("-", (name or "").lower()).strip("-")
    return slug[:60] or "memory"


@dataclass
class Note:
    name: str
    description: str
    type: str = "user"
    body: str = ""
    scope: str = "global"
    id: str = field(default_factory=lambda: uuid.uuid4().hex)
    created: str = field(default_factory=lambda: date.today().isoformat())
    updated: str = field(default_factory=lambda: date.today().isoformat())

    def index_line(self) -> str:
        return f"- {self.name} ({self.type}) — {self.description}"

    def to_markdown(self) -> str:
        front = {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "type": self.type,
            "scope": self.scope,
            "created": self.created,
            "updated": self.updated,
        }
        head = yaml.safe_dump(front, allow_unicode=True, sort_keys=False).strip()
        return f"---\n{head}\n---\n{self.body.strip()}\n"

    @classmethod
    def from_markdown(cls, text: str, fallback_name: str) -> Note | None:
        if not text.startswith("---"):
            return None
        parts = text.split("---", 2)
        if len(parts) < 3:
            return None
        try:
            front = yaml.safe_load(parts[1]) or {}
        except yaml.YAMLError:
            return None
        if not isinstance(front, dict):
            return None
        note_type = str(front.get("type", "user"))
        return cls(
            name=str(front.get("name") or fallback_name),
            description=str(front.get("description", "")),
            type=note_type if note_type in NOTE_TYPES else "user",
            body=parts[2].strip(),
            scope=str(front.get("scope", "global")),
            id=str(front.get("id") or uuid.uuid4().hex),
            created=str(front.get("created", date.today().isoformat())),
            updated=str(front.get("updated", date.today().isoformat())),
        )


class NoteStore(Protocol):
    def save(self, note: Note) -> Note: ...
    def get(self, name: str) -> Note | None: ...
    def delete(self, name: str) -> bool: ...
    def all(self) -> list[Note]: ...
    def search(self, query: str, limit: int = 8) -> list[tuple[Note, float]]: ...
    def location(self) -> Path: ...


class FileNoteStore:
    """Local backend: one .md file per memory in the owner's folder."""

    def __init__(self, owner: str = "default", root: Path | None = None):
        self.owner = owner
        base = root if root is not None else store._db_path().parent / "notes"
        self.dir = base / slugify(owner)
        self.dir.mkdir(parents=True, exist_ok=True)

    def location(self) -> Path:
        return self.dir

    def _path(self, name: str) -> Path:
        return self.dir / f"{slugify(name)}.md"

    def save(self, note: Note) -> Note:
        note.name = slugify(note.name)
        if note.type not in NOTE_TYPES:
            raise ValueError(f"type must be one of {', '.join(NOTE_TYPES)}")
        existing = self.get(note.name)
        if existing is not None:
            note.id = existing.id
            note.created = existing.created
        note.updated = date.today().isoformat()
        self._path(note.name).write_text(note.to_markdown(), encoding="utf-8")
        self._write_index()
        return note

    def get(self, name: str) -> Note | None:
        path = self._path(name)
        if not path.exists():
            return None
        return Note.from_markdown(path.read_text(encoding="utf-8"), path.stem)

    def delete(self, name: str) -> bool:
        path = self._path(name)
        if not path.exists():
            return False
        path.unlink()
        self._write_index()
        return True

    def all(self) -> list[Note]:
        notes = []
        for path in sorted(self.dir.glob("*.md")):
            if path.name == "INDEX.md":
                continue
            try:
                note = Note.from_markdown(path.read_text(encoding="utf-8"), path.stem)
            except OSError:
                continue
            if note is not None:
                notes.append(note)
        return notes

    def search(self, query: str, limit: int = 8) -> list[tuple[Note, float]]:
        notes = self.all()
        scores = bm25_scores(query, [f"{n.name} {n.description} {n.body}" for n in notes])
        ranked = sorted(zip(notes, scores), key=lambda p: p[1], reverse=True)
        return [(n, s) for n, s in ranked if s > 0][:limit]

    def _write_index(self) -> None:
        lines = ["# OpenBro memory index (generated — edit the note files, not this)", ""]
        lines += [n.index_line() for n in sorted(self.all(), key=lambda n: (n.type, n.name))]
        (self.dir / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_note_store(owner: str, config: dict | None = None) -> NoteStore:
    backend = ((config or {}).get("storage", {}) or {}).get("backend", "local")
    if backend == "local":
        return FileNoteStore(owner)
    if backend == "remote":
        raise NotImplementedError(
            "storage.backend 'remote' needs the OpenBro server (planned for v2)."
        )
    raise ValueError(f"Unknown storage.backend: {backend!r}")


# ─── selecting what goes into the prompt ─────────────────────────────


def in_scope(note: Note, project_root: str | None) -> bool:
    if note.scope == "global" or not note.scope.startswith("project:"):
        return True
    if not project_root:
        return False
    want = note.scope[len("project:") :].strip()
    return Path(want).resolve() == Path(project_root).resolve()


def memory_block(
    notes: list[Note],
    query: str,
    project_root: str | None,
    budget_tokens: int = 1500,
) -> str:
    """Prompt block of the memories that matter for this turn.

    Always: `user` and `feedback` notes (who the user is, how to behave).
    Then project notes for the current repo and the best BM25 matches for
    the user's message, by score then recency, until the budget is used.
    Bodies are inlined only when everything fits; otherwise index lines
    and the model reads full notes with `memory read`.
    """
    visible = [n for n in notes if in_scope(n, project_root)]
    if not visible:
        return ""
    budget_chars = budget_tokens * 4
    full = [f"- {n.name} ({n.type}): {n.description}\n  {n.body}" for n in visible]
    if sum(len(x) for x in full) <= budget_chars:
        return "## MEMORY (what you know about this user)\n" + "\n".join(full)

    always = [n for n in visible if n.type in ("user", "feedback")]
    rest = [n for n in visible if n.type not in ("user", "feedback")]
    scores = bm25_scores(query, [f"{n.name} {n.description} {n.body}" for n in rest])
    rest_ranked = [
        n
        for n, _ in sorted(
            zip(rest, scores),
            key=lambda p: (p[1], p[0].scope != "global", p[0].updated),
            reverse=True,
        )
    ]
    lines, used, shown = [], 0, 0
    for n in always + rest_ranked:
        line = n.index_line()
        if used + len(line) > budget_chars:
            break
        lines.append(line)
        used += len(line) + 1
        shown += 1
    hidden = len(visible) - shown
    out = "## MEMORY (index — call `memory` action=read for a note's full text)\n" + "\n".join(
        lines
    )
    if hidden > 0:
        out += f"\n(+{hidden} more memories — use `memory` action=search)"
    return out
